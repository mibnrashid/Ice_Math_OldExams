"""Build the website data and the practice PDFs from src/<course>/*.json.

Usage:
  python -I tools/build.py                 # all courses, all exams
  python -I tools/build.py math208         # one course
  python -I tools/build.py math208 253-fx  # one exam
  add --no-pdf to skip LaTeX

Each exam is shuffled once with a seed made from course-term-kind, so the website and the PDF
always show the same question order and the same choice order.
"""
