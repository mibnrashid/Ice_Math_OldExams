import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, DATA, PDF = ROOT / "src", ROOT / "data", ROOT / "pdf"

COURSES = {
    "math101": "Math 101",
    "math102": "Math 102",
    "math201": "Math 201",
    "math208": "Math 208",
    "stat201": "Stat 201",
}
KINDS = {"e1": "Major Exam I", "e2": "Major Exam II", "fx": "Final Exam"}
SHORT = {"e1": "Major1", "e2": "Major2", "fx": "Final"}
L = "abcde"
SUBTITLE_HTML = ('<p style="font-family:LMItalic;font-style:italic;font-size:10.91pt;text-align:center;margin:0">'
                 'Student effort not Official. Generated by Ice <span style="font-family:Sym;font-style:normal">&#x2744;</span>. '
                 '<bdi dir="rtl" lang="ar" style="font-family:Arabic;font-style:normal;font-size:11.5pt">دعواتكم له</bdi></p>')


def season(term):
    yy, s = int(term[:2]), term[2]
    return {"1": f"Fall 20{yy}", "2": f"Spring 20{yy + 1}", "3": f"Summer 20{yy + 1}"}[s]


def shuffled(course, d):
    rng = random.Random(f"{course}-{d['term']}-{d['kind']}")
    # Written questions stay after the multiple-choice part, shuffled among themselves.
    # Omitted placeholders (missing from the source) go last, in master order.
    order = [i for i, q in enumerate(d["qs"]) if not q.get("written") and not q.get("omitted")]
    written = [i for i, q in enumerate(d["qs"]) if q.get("written")]
    omitted = [i for i, q in enumerate(d["qs"]) if q.get("omitted")]
    rng.shuffle(order)
    out = []
    for i in order:
        q = dict(d["qs"][i])
        perm = list(range(len(q["opts"])))
        if not q.get("lock"):
            rng.shuffle(perm)
        q["opts"] = [q["opts"][j] for j in perm]
        q["ans"] = perm.index(q["ans"])
        q["orig"] = i + 1
        out.append(q)
    if written:
        rng.shuffle(written)
        out += [dict(d["qs"][i], orig=i + 1) for i in written]
    out += [dict(d["qs"][i], orig=i + 1) for i in omitted]
    return out


def sec_key(s):
    m = re.match(r"(\d+)\.(\d+)", s)
    return (int(m.group(1)), int(m.group(2))) if m else (int(re.sub(r"\D", "", s) or 0), 0)


# ---------- LaTeX ----------

def tex_text(t):
    """Escape a non-maths chunk for LaTeX (validate.py already bans % & # _ ^ and commands)."""
    t = t.replace("\\", "").replace("{", r"\{").replace("}", r"\}")
    t = t.replace("<", r"$<$").replace(">", r"$>$").replace("~", r"\textasciitilde{}").replace("|", r"$|$")
    t = re.sub(r'"([^"]*)"', r"``\1''", t)
    return t


def tex(s):
    out, i, n, buf = [], 0, len(s), ""
    while i < n:
        if s.startswith("\\[", i):
            j = s.index("\\]", i + 2)
            out.append(tex_text(buf)); buf = ""
            out.append(s[i:j + 2]); i = j + 2
        elif s[i] == "$":
            j = i + 1
            while not (s[j] == "$" and s[j - 1] != "\\"):
                j += 1
            out.append(tex_text(buf)); buf = ""
            out.append(s[i:j + 1]); i = j + 1
        else:
            buf += s[i]; i += 1
    out.append(tex_text(buf))
    return "".join(out)


PREAMBLE = r"""\documentclass[11pt]{article}
\usepackage[a4paper,margin=22mm,headheight=14pt]{geometry}
\usepackage{amsmath,amssymb}
\usepackage{graphicx}
\usepackage{enumitem}
\usepackage{array}
\usepackage{fancyhdr}
\pagestyle{fancy}
\fancyhf{}
\lhead{\small HEADER}
\rhead{\small Page \thepage}
\renewcommand{\headrulewidth}{0.4pt}
\setlength{\parindent}{0pt}
\setlength{\parskip}{0pt}
\setlist[enumerate]{label=(\alph*),leftmargin=28.4pt,itemsep=5pt,topsep=9pt}
\begin{document}
"""


KEY_HEAD = r"""\begin{center}
\begin{tabular}{>{\centering\arraybackslash}p{19.2pt}>{\centering\arraybackslash}p{34.5pt}p{374.2pt}}
\hline
\textbf{Q} & \textbf{Ans} & \textbf{Brief explanation}\\
\hline
"""
KEY_FOOT = "\\end{tabular}\n\\end{center}"


def orig_course(d):
    """Old STAT 319 exams are listed under Stat 201; say so on the site and in the PDF."""
    return "STAT 319" if d.get("source", "").startswith("stat319") else None


def build_tex(course, d, qs):
    cname, kname, term = COURSES[course], KINDS[d["kind"]], d["term"][:3]
    if d.get("version"):  # two different exams in one term (e.g. Math 201 251 Major II A and B)
        term += " (Version %s)" % d["version"]
    t = [PREAMBLE.replace("HEADER", f"{term}, {cname}, {kname} (Practice, shuffled)")]
    t.append(r"""\begin{center}
{\large\bfseries King Fahd University of Petroleum and Minerals}\\[2pt]
{\bfseries Department of Mathematics}\\[2pt]
\rule{0pt}{14pt}\\[4pt]
{\Large\bfseries %s \quad %s \quad Term %s}\\[4pt]
Original exam date: %s. \quad Practice version: questions and choices shuffled.\\[2pt]
Net time allowed: %d minutes%s
\end{center}
\vspace{2pt}\hrule\vspace{14pt}
""" % (cname, kname, term, d["date"] or "not printed", d["minutes"],
       r" \quad Original course: %s" % orig_course(d) if orig_course(d) else ""))
    for n, q in enumerate(qs, 1):
        t.append(r"\noindent\begin{minipage}{\linewidth}" + "\n")
        t.append(r"\textbf{%d.} %s" % (n, tex(q["q"])) + "\n")
        if q.get("img"):
            t.append(r"\begin{center}\includegraphics[width=0.6\linewidth]{%s}\end{center}" % (SRC / course / "img" / q["img"]).as_posix() + "\n")
        if q.get("written"):
            t.append(r"\end{minipage}" + "\n\n" + r"\vspace{150pt}" + "\n\n")
            continue
        if q.get("omitted"):
            t.append(r"\end{minipage}" + "\n\n" + r"\vspace{14pt}" + "\n\n")
            continue
        t.append(r"\begin{enumerate}" + "\n")
        for o in q["opts"]:
            t.append(r"\item %s" % tex(o) + "\n")
        t.append(r"\end{enumerate}" + "\n" + r"\end{minipage}" + "\n\n" + r"\vspace{14pt}" + "\n\n")
    t.append(r"""\newpage
\begin{center}
{\Large\bfseries Answer Key}\\[2pt]
\rule{0pt}{14pt}
\end{center}
\vspace{3pt}
{\renewcommand{\arraystretch}{1.9}
""" + KEY_HEAD)
    # A tabular can't break across pages, so a long key (28-question finals) is split in two halves.
    split = (len(qs) + 1) // 2 if len(qs) > 21 else None
    for n, q in enumerate(qs, 1):
        if q.get("omitted"):
            t.append(r"%d & {\footnotesize omitted} & Omitted.\\ \hline" % n + "\n")
            if n == split:
                t.append(KEY_FOOT + "\\newpage\n" + KEY_HEAD)
            continue
        t.append(r"%d & %s & %s\\ \hline" % (n, r"{\footnotesize written}" if q.get("written") else r"\textbf{(%s)}" % L[q["ans"]], tex(re.sub(r"\[dt]?frac", r"\tfrac", q["brief"]))) + "\n")
        if n == split:
            t.append(KEY_FOOT + "\\newpage\n" + KEY_HEAD)
    t.append(KEY_FOOT + "}\n\\end{document}\n")
    return "".join(t)


def find_tex():
    exe = shutil.which("pdflatex")
    if exe:
        return exe
    p = Path(os.environ.get("APPDATA", "")) / "TinyTeX" / "bin" / "windows" / "pdflatex.exe"
    return str(p) if p.exists() else None


def stamp(pdf_path):
    """Add the italic credit line (with the snowflake and Arabic) under the title on page 1 and the key page."""
    import pymupdf
    fonts = ROOT / "tools" / "fonts"
    css = (f'@font-face{{font-family:LMItalic;src:url("{(fonts / "lmroman10-italic.otf").as_posix()}")}}'
           f'@font-face{{font-family:Arabic;src:url("{(fonts / "NotoNaskhArabic-Regular.ttf").as_posix()}")}}'
           '@font-face{font-family:Sym;src:url("C:/Windows/Fonts/seguisym.ttf")}')
    arch = pymupdf.Archive(str(fonts))
    doc = pymupdf.open(pdf_path)
    # The key can span two pages on long exams, so find its first page by the heading.
    key = next(p.number for p in doc if "Answer Key" in p.get_text())
    for pno in (0, key):
        page = doc[pno]
        # The empty 14pt line reserved under "Department of Mathematics" / "Answer Key".
        y = 92.8 if pno == 0 else 77.2
        page.insert_htmlbox(pymupdf.Rect(62.36, y, 532.91, y + 22), SUBTITLE_HTML, css=css, archive=arch)
    doc.subset_fonts()
    doc.save(pdf_path + ".tmp", garbage=4, deflate=True)
    doc.close()
    os.replace(pdf_path + ".tmp", pdf_path)


def build_pdf(course, d, qs, out):
    exe = find_tex()
    if not exe:
        raise SystemExit("pdflatex not found (install TinyTeX)")
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "exam.tex").write_text(build_tex(course, d, qs), encoding="utf-8")
        r = subprocess.run([exe, "-interaction=nonstopmode", "-halt-on-error", "exam.tex"], cwd=tmp,
                           capture_output=True, text=True, encoding="utf-8", errors="replace")
        if r.returncode:
            log = (Path(tmp) / "exam.log").read_text(encoding="utf-8", errors="replace")
            err = log[log.find("\n!"):][:1500] if "\n!" in log else r.stdout[-1500:]
            raise SystemExit(f"LaTeX failed for {course} {d['term']}-{d['kind']}:\n{err}")
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(Path(tmp) / "exam.pdf", out)
    stamp(str(out))


# ---------- main ----------

def main(argv):
    pdf = "--no-pdf" not in argv
    args = [a for a in argv if not a.startswith("--")]
    courses = [args[0]] if args else [c for c in COURSES if (SRC / c).is_dir()]
    only = args[1] if len(args) > 1 else None
    for course in courses:
        exams = []
        for f in sorted((SRC / course).glob("*.json")):
            d = json.loads(f.read_text(encoding="utf-8"))
            qs = shuffled(course, d)
            name = f"{course}-{d['term']}-{d['kind']}-practice.pdf"
            exams.append({
                "term": d["term"], "kind": d["kind"], "date": d["date"], "season": season(d["term"]),
                "minutes": d["minutes"], "pdf": f"pdf/{course}/{name}",
                "dl": f"{COURSES[course].replace(' ', '')}-{d['term']}-{SHORT[d['kind']]}-Practice.pdf",
                **({"orig": orig_course(d)} if orig_course(d) else {}),
                **({"version": d["version"]} if d.get("version") else {}),
                "secs": sorted({q["sec"] for q in d["qs"] if "sec" in q}, key=sec_key),
                "qs": [{k: q[k] for k in ("sec", "q", "opts", "ans", "written", "answer", "omitted", "hints", "steps", "img") if k in q} for q in qs],
            })
            if pdf and (only is None or only == f.stem):
                build_pdf(course, d, qs, PDF / course / name)
                print("pdf", course, f.stem)
        for q in (SRC / course / "img").glob("*") if (SRC / course / "img").is_dir() else []:
            (ROOT / "img" / course).mkdir(parents=True, exist_ok=True)
            shutil.copy(q, ROOT / "img" / course / q.name)
        exams.sort(key=lambda e: (e["kind"], -int(e["term"][:3]), e["term"]))
        DATA.mkdir(exist_ok=True)
        js = "window.ICE_DATA=window.ICE_DATA||{};ICE_DATA[%s]=%s;\n" % (
            json.dumps(course), json.dumps(exams, ensure_ascii=False, separators=(",", ":")))
        (DATA / f"{course}.js").write_text(js, encoding="utf-8")
        print("data", course, len(exams), "exams")
    tpl = (ROOT / "tools" / "index.template.html").read_text(encoding="utf-8")
    fonts = (ROOT / "tools" / "web-fonts.css").read_text(encoding="utf-8").strip()
    (ROOT / "index.html").write_text(tpl.replace("/*FONTS*/", fonts), encoding="utf-8")
    (ROOT / ".nojekyll").touch()
    manifest = {c: sorted({p.stem.split("-")[1] for p in (SRC / c).glob("*.json")}) for c in COURSES if (SRC / c).is_dir()}
    # Month-day of every dated exam, so the home page can highlight the exam kind that is coming up next.
    months = {m: i for i, m in enumerate(["January", "February", "March", "April", "May", "June", "July", "August",
                                          "September", "October", "November", "December"], 1)}
    dates = {k: set() for k in KINDS}
    for f in SRC.glob("*/*.json"):
        d = json.loads(f.read_text(encoding="utf-8"))
        if d.get("date"):
            day, month, _ = d["date"].split()
            dates[d["kind"]].add("%02d-%02d" % (months[month], int(day)))
    (DATA / "courses.js").write_text("window.ICE_COURSES=%s;\nwindow.ICE_DATES=%s;\n" % (
        json.dumps(manifest), json.dumps({k: sorted(v) for k, v in dates.items()})), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1:])
